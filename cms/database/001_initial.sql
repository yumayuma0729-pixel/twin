CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(190) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','editor','support') NOT NULL DEFAULT 'editor',
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS contents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 type ENUM('vehicle','story','news','column') NOT NULL,
 slug VARCHAR(160) NOT NULL,
 title VARCHAR(200) NOT NULL,
 draft LONGTEXT NOT NULL,
 published LONGTEXT NULL,
 published_at DATETIME NULL,
 public_updated_at DATETIME NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_by BIGINT UNSIGNED NOT NULL,
 version INT NOT NULL DEFAULT 1,
 deleted_at DATETIME NULL,
 UNIQUE KEY content_slug (type,slug),
 KEY content_listing (type,deleted_at,published_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS media (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 filename VARCHAR(100) NOT NULL UNIQUE, mime VARCHAR(60) NOT NULL,
 width INT NOT NULL, height INT NOT NULL, bytes INT NOT NULL,
 alt VARCHAR(250) NOT NULL, created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_media (
 content_id BIGINT UNSIGNED NOT NULL, media_id BIGINT UNSIGNED NOT NULL,
 state ENUM('draft','published') NOT NULL,
 PRIMARY KEY(content_id,media_id,state),
 FOREIGN KEY(content_id) REFERENCES contents(id) ON DELETE CASCADE,
 FOREIGN KEY(media_id) REFERENCES media(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS inquiries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 submission_key CHAR(64) NOT NULL UNIQUE,
 type VARCHAR(30) NOT NULL, name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL,
 phone VARCHAR(30) NOT NULL DEFAULT '', message TEXT NOT NULL,
 vehicle_id BIGINT UNSIGNED NULL,
 vehicle_title VARCHAR(200) NOT NULL DEFAULT '',
 status ENUM('new','in_progress','closed') NOT NULL DEFAULT 'new',
 assigned_to BIGINT UNSIGNED NULL, note TEXT NOT NULL,
 consent_version VARCHAR(30) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 version INT NOT NULL DEFAULT 1,
 KEY inquiry_listing (status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 inquiry_id BIGINT UNSIGNED NOT NULL UNIQUE,
 state ENUM('pending','processing','accepted','failed') NOT NULL DEFAULT 'pending',
 attempts INT NOT NULL DEFAULT 0, last_error VARCHAR(200) NOT NULL DEFAULT '',
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(inquiry_id) REFERENCES inquiries(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) PRIMARY KEY,
 hits INT NOT NULL DEFAULT 1, window_started BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NULL, action VARCHAR(50) NOT NULL,
 target_type VARCHAR(30) NOT NULL, target_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
